<?php

namespace App\Enums;

/** Where an alternative ticket PDF came from (internal only; never shown to the customer). */
enum DocumentSource: string
{
    use HasOptions;

    case CustomerProvided = 'customer_provided';
    case SupplierProvided = 'supplier_provided';
    case AirlineAlternative = 'airline_alternative';
    case OtherAuthorized = 'other_authorized';
    /** Created by the system from the booking records (never chosen when uploading a file). */
    case AgencyGenerated = 'agency_generated';

    /** Sources a person can pick when uploading a file. @return list<array{value: string, label: string}> */
    public static function uploadOptions(): array
    {
        return array_values(array_filter(self::options(), fn ($o) => $o['value'] !== self::AgencyGenerated->value));
    }

    public function label(): string
    {
        return match ($this) {
            self::CustomerProvided => 'Customer-provided',
            self::SupplierProvided => 'Supplier-provided',
            self::AirlineAlternative => 'Airline-provided (alternative channel)',
            self::OtherAuthorized => 'Other authorized source',
            self::AgencyGenerated => 'Generated by the agency from booking records',
        };
    }
}
