<?php

namespace App\Services;

use App\Enums\BookingStatus;
use App\Enums\DocumentSource;
use App\Enums\DocumentType;
use App\Enums\FlightStatus;
use App\Enums\VerificationStatus;
use App\Models\Booking;
use App\Models\BookingFlight;
use App\Models\Document;
use App\Models\Passenger;
use App\Models\User;
use Barryvdh\DomPDF\Facade\Pdf;
use Carbon\CarbonImmutable;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Storage;
use Illuminate\Support\Str;
use Illuminate\Validation\ValidationException;
use Throwable;

/**
 * Builds the agency's ticket PDF (one per passenger) from the booking's own records, for when the
 * official e-ticket has not arrived yet. The reservation code and airline PNR are entered by staff
 * when creating it and are always printed; the ticket number and the internal booking reference are
 * never printed. Nothing is invented: fields that are not recorded are left out.
 *
 * The PDF is stored as an alternative ticket PDF ("Generated by the agency"). It is built from the
 * agency's own records by the staff member who creates it (after the preview), so it is recorded as
 * verified by that person; it can still be rejected later. It never creates tickets or changes statuses.
 */
class GeneratedTicketService
{
    /** Bookings that are only an enquiry or are cancelled have no reservation to document. */
    private const NOT_ALLOWED = [BookingStatus::Inquiry, BookingStatus::Cancelled];

    /** Segments are shown as confirmed (HK) only once the reservation is confirmed. */
    private const CONFIRMED = [BookingStatus::Confirmed, BookingStatus::Ticketed, BookingStatus::Changed, BookingStatus::Completed];

    public function __construct(private AgencyBrandingService $branding) {}

    /** Why no ticket PDF can be created for this booking (empty = OK). @return list<string> */
    public function problems(Booking $booking): array
    {
        $booking->loadMissing(['passengers', 'flights']);
        $problems = [];
        if (in_array($booking->status, self::NOT_ALLOWED, true)) {
            $problems[] = $booking->status === BookingStatus::Cancelled
                ? 'This booking is cancelled.'
                : 'This booking is still an inquiry. Confirm the reservation first.';
        }
        if ($booking->passengers->isEmpty()) {
            $problems[] = 'Add the passengers first.';
        }
        if ($booking->flights->isEmpty()) {
            $problems[] = 'Add the flight segments first (flight number, route and departure time).';
        }
        foreach ($booking->flights as $i => $f) {
            if (! $f->flight_number || ! $f->origin_code || ! $f->destination_code || ! $f->departure_at) {
                $problems[] = 'Flight '.($i + 1).' is missing its flight number, route or departure time.';
            }
        }

        return $problems;
    }

    /**
     * The reservation code and airline PNR to print, checked and upper-cased.
     *
     * @return array{reservation_code: string, airline_pnr: string}
     */
    public function codes(array $input): array
    {
        $codes = $errors = [];
        foreach (['reservation_code' => 'reservation code', 'airline_pnr' => 'airline PNR'] as $field => $label) {
            $value = strtoupper(preg_replace('/\s+/', '', (string) ($input[$field] ?? '')));
            if ($value === '') {
                $errors[$field] = "Enter the $label.";
            } elseif (! preg_match('/^[A-Z0-9]{4,10}$/', $value)) {
                $errors[$field] = "The $label must be 4 to 10 letters or digits.";
            }
            $codes[$field] = $value;
        }
        if ($errors) {
            throw ValidationException::withMessages($errors);
        }

        return $codes;
    }

    /**
     * The rendered PDF for one passenger (used for preview and storage).
     *
     * @param  array{reservation_code: string, airline_pnr: string}  $codes
     */
    public function render(Booking $booking, Passenger $passenger, array $codes): string
    {
        return Pdf::loadView('pdf.ticket', $this->viewData($booking, $passenger, $codes))
            ->setPaper('a4')
            ->setOption(['defaultFont' => 'DejaVu Sans', 'isRemoteEnabled' => false, 'isPhpEnabled' => false, 'isFontSubsettingEnabled' => true])
            ->output();
    }

    /**
     * Creates and stores one PDF per selected passenger.
     *
     * @param  list<int>|null  $passengerIds  null = every passenger
     * @return list<Document>
     */
    public function generate(Booking $booking, ?array $passengerIds, array $codes, User $user): array
    {
        if ($problems = $this->problems($booking)) {
            throw ValidationException::withMessages(['booking' => $problems]);
        }
        $passengers = $booking->passengers;
        if ($passengerIds !== null) {
            $passengers = $passengers->whereIn('id', array_map('intval', $passengerIds))->values();
            if ($passengers->count() !== count(array_unique($passengerIds))) {
                throw ValidationException::withMessages(['passenger_ids' => 'Choose passengers of this booking.']);
            }
        }

        $stored = [];
        try {
            return DB::transaction(function () use ($booking, $passengers, $codes, $user, &$stored) {
                return $passengers->map(function (Passenger $p) use ($booking, $codes, $user, &$stored) {
                    $key = now()->format('Y/m').'/'.Str::uuid()->toString().'.pdf';
                    $pdf = $this->render($booking, $p, $codes);
                    Storage::disk(DocumentStorageService::DISK)->put($key, $pdf);
                    $stored[] = $key;

                    return Document::create([
                        'booking_id' => $booking->id,
                        'passenger_id' => $p->id,
                        'document_type' => DocumentType::AlternativeTicket,
                        'source_type' => DocumentSource::AgencyGenerated,
                        'verification_status' => VerificationStatus::Verified,
                        'verified_by' => $user->id,
                        'verified_at' => now(),
                        'original_name' => $this->filename($p, $codes['airline_pnr']),
                        'storage_key' => $key,
                        'mime_type' => 'application/pdf',
                        'size_bytes' => strlen($pdf),
                        'notes' => "Created from the booking records while the official e-ticket is not available. Reservation code {$codes['reservation_code']}, airline PNR {$codes['airline_pnr']}.",
                        'uploaded_by' => $user->id,
                    ]);
                })->all();
            });
        } catch (Throwable $e) {
            Storage::disk(DocumentStorageService::DISK)->delete($stored);
            throw $e;
        }
    }

    // ------------------------------------------------------------------ template data

    private function activeTicket(Booking $booking, Passenger $passenger)
    {
        return $booking->tickets->where('passenger_id', $passenger->id)->first(fn ($t) => $t->isActive() && $t->ticket_number);
    }

    private function filename(Passenger $p, string $pnr): string
    {
        return 'ticket-'.$pnr.'-'.Str::slug(Str::limit($p->full_name_as_document, 40, '')).'.pdf';
    }

    /**
     * @param  array{reservation_code: string, airline_pnr: string}  $codes
     * @return array<string, mixed>
     */
    public function viewData(Booking $booking, Passenger $passenger, array $codes): array
    {
        $booking->loadMissing(['flights', 'tickets']);
        $ticket = $this->activeTicket($booking, $passenger);
        $airports = $this->airports();
        $confirmed = in_array($booking->status, self::CONFIRMED, true);

        $segments = $booking->flights->map(function (BookingFlight $f) use ($airports, $confirmed) {
            $from = $airports[$f->origin_code] ?? null;
            $to = $airports[$f->destination_code] ?? null;

            return [
                'date' => $f->departure_at?->format('l, d M Y'),
                'cabin' => $f->cabin_class?->label(),
                'flight' => trim($this->airlineCode($f->flight_number).' '.$this->flightDigits($f->flight_number)),
                'airline' => $f->airline,
                'from' => ['code' => $f->origin_code, 'name' => $from['name'] ?? null, 'city' => $from['city'] ?? null],
                'to' => ['code' => $f->destination_code, 'name' => $to['name'] ?? null, 'city' => $to['city'] ?? null],
                'departure' => $f->departure_at?->format('d M Y · H:i'),
                'arrival' => $f->arrival_at?->format('d M Y · H:i'),
                'duration' => $this->duration($f),
                'status' => match (true) {
                    $f->status === FlightStatus::Cancelled => 'Cancelled',
                    $confirmed => 'HK',
                    default => 'Not confirmed',
                },
                'baggage' => $f->baggage_allowance,
            ];
        })->values()->all();

        $agency = $this->branding->agency();

        return [
            'agency' => $agency,
            'passengerName' => $passenger->full_name_as_document,
            'reservationCode' => $codes['reservation_code'],
            'airlinePnr' => $codes['airline_pnr'],
            // The ticket's issue date when recorded, otherwise the date this document is issued.
            'issueDate' => ($ticket?->issued_at ?? now())->format('Y-m-d'),
            'segments' => $segments,
            'generatedAt' => now('UTC')->format('d M Y \a\t H:i'),
        ];
    }

    /** "EY391" / "EY 391" -> "EY" and "391" (two-character airline designator). */
    private function airlineCode(string $flight): string
    {
        $flight = strtoupper(str_replace(' ', '', $flight));

        return preg_match('/^([A-Z0-9]{2})(\d{1,4}[A-Z]?)$/', $flight, $m) ? $m[1] : $flight;
    }

    private function flightDigits(string $flight): string
    {
        $flight = strtoupper(str_replace(' ', '', $flight));

        return preg_match('/^([A-Z0-9]{2})(\d{1,4}[A-Z]?)$/', $flight, $m) ? $m[2] : '';
    }

    /** Flight time only when both airport timezones are recorded (local times alone can't give it). */
    private function duration(BookingFlight $f): ?string
    {
        if (! $f->departure_at || ! $f->arrival_at || ! $f->origin_timezone || ! $f->destination_timezone) {
            return null;
        }
        try {
            $dep = CarbonImmutable::parse($f->departure_at->format('Y-m-d H:i:s'), $f->origin_timezone);
            $arr = CarbonImmutable::parse($f->arrival_at->format('Y-m-d H:i:s'), $f->destination_timezone);
        } catch (Throwable) {
            return null;
        }
        $minutes = (int) $dep->diffInMinutes($arr, false);

        return $minutes > 0 ? sprintf('%02dh %02dm', intdiv($minutes, 60), $minutes % 60) : null;
    }

    /** @return array<string, array{code: string, city: string, name: string, country: string}> */
    private function airports(): array
    {
        return once(fn () => collect(json_decode((string) file_get_contents(resource_path('data/airports.json')), true) ?: [])->keyBy('code')->all());
    }
}
